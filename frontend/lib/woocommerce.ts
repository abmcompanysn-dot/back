/**
 * Version allégée d'un WooProduct pour la persistance panier (localStorage).
 * CartPage/CheckoutPage/le compteur panier ne lisent jamais description,
 * images (galerie complète), variations, attributes ou defaultAttributes —
 * les garder dans le panier persisté ne fait que gonfler inutilement chaque
 * ligne et finit par dépasser le quota localStorage (~5-10 Mo) dès qu'on a
 * quelques produits différents dans le panier, ce qui faisait planter toute
 * l'app (QuotaExceededError non interceptée sur le useEffect de persistance).
 */
export function toCartProduct(product: WooProduct): WooProduct {
  return {
    id: product.id,
    name: product.name,
    slug: product.slug,
    price: product.price,
    regularPrice: product.regularPrice,
    salePrice: product.salePrice,
    currency: product.currency,
    type: product.type,
    image: product.image,
    category: product.category,
    categories: product.categories,
    categorySlug: product.categorySlug,
    vendor: product.vendor,
    country: product.country,
    countryCode: product.countryCode,
    stock: product.stock,
    inStock: product.inStock,
    description: '',
    lang: product.lang,
    weight: product.weight,
  }
}

// Format price consistently (avoids hydration mismatch)
// Prices are in USD ($)
export function formatPrice(price: number): string {
  if (price === 0) return '0.00'
  return price.toFixed(2).replace(/\B(?=(\d{3})+(?!\d))/g, ',')
}

